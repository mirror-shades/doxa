//! Generate the flat `ZigError` enum from the bundled Zig standard library.
//!
//! `@typeInfo(anyerror).error_set` is null, and Zig has no reflection over a
//! module's declarations, so the names come from the source: every identifier
//! in an `error{...}` set and every `error.Name` reference. Over-collection is
//! harmless (an extra enum variant is just an extra name) and under-collection
//! is caught when a block names a missing error.
//!
//! Usage:
//!   gen_zerr <zig-std-dir> <output-file>
//!   gen_zerr <zig-std-dir> <output-file> --check

const std = @import("std");

const header =
    \\# Generated by scripts/gen_zerr.zig from the bundled Zig standard library.
    \\# Do not edit by hand; run `zig build zerr` to regenerate.
    \\
    \\module error from "../error.doxa"
    \\
    \\# Every failure a std function reports: an error Zig raised, named as Zig
    \\# names it, or one of Doxa's own runtime errors.
    \\public group StdError {
    \\    ZigError,
    \\    error.Method
    \\}
    \\
    \\# Every error name the bundled Zig standard library defines.
    \\public enum ZigError {
    \\
;

const max_file_bytes = 16 * 1024 * 1024;

pub fn main(init: std.process.Init) !void {
    const allocator = init.arena.allocator();
    const args = try init.minimal.args.toSlice(allocator);

    if (args.len < 3 or args.len > 4) {
        std.debug.print("usage: gen_zerr <zig-std-dir> <output-file> [--check]\n", .{});
        std.process.exit(1);
    }
    const std_dir = args[1];
    const out_path = args[2];
    const check = args.len == 4 and std.mem.eql(u8, args[3], "--check");

    var names = std.StringHashMap(void).init(allocator);
    defer names.deinit();

    var dir = std.Io.Dir.cwd().openDir(init.io, std_dir, .{ .iterate = true }) catch |err| {
        std.debug.print("gen_zerr: cannot open {s}: {s}\n", .{ std_dir, @errorName(err) });
        std.process.exit(1);
    };
    defer dir.close(init.io);

    var walker = try dir.walk(allocator);
    defer walker.deinit();

    var file_count: usize = 0;
    while (try walker.next(init.io)) |entry| {
        if (entry.kind != .file) continue;
        if (!std.mem.endsWith(u8, entry.path, ".zig")) continue;
        file_count += 1;

        var file_arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
        defer file_arena.deinit();
        const file_alloc = file_arena.allocator();

        const source = entry.dir.readFileAllocOptions(
            init.io,
            entry.basename,
            file_alloc,
            .limited(max_file_bytes),
            .of(u8),
            0,
        ) catch |err| {
            std.debug.print("gen_zerr: cannot read {s}: {s}\n", .{ entry.path, @errorName(err) });
            std.process.exit(1);
        };

        var ast = std.zig.Ast.parse(file_alloc, source, .zig) catch |err| {
            std.debug.print("gen_zerr: cannot parse {s}: {s}\n", .{ entry.path, @errorName(err) });
            std.process.exit(1);
        };
        defer ast.deinit(file_alloc);
        if (ast.errors.len != 0) {
            std.debug.print("gen_zerr: cannot parse {s}\n", .{entry.path});
            std.process.exit(1);
        }

        // Names inside `test` declarations are fixtures, not errors the bundled
        // std can return. Collect the ranges first so a name that also appears
        // in real code is still included.
        var test_ranges: std.ArrayList(TokenRange) = .empty;
        for (0..ast.nodes.len) |i| {
            const node: std.zig.Ast.Node.Index = @enumFromInt(i);
            if (ast.nodeTag(node) == .test_decl) {
                try test_ranges.append(file_alloc, .{ .start = ast.firstToken(node), .end = ast.lastToken(node) });
            }
        }

        const tags = ast.tokens.items(.tag);
        for (0..ast.nodes.len) |i| {
            const node: std.zig.Ast.Node.Index = @enumFromInt(i);
            switch (ast.nodeTag(node)) {
                .error_set_decl => {
                    const range = ast.nodeData(node).token_and_token;
                    var t = range[0] + 1;
                    while (t < range[1]) : (t += 1) {
                        if (tags[t] == .identifier and !inTestRange(t, test_ranges.items)) {
                            try addName(allocator, &names, ast.tokenSlice(t));
                        }
                    }
                },
                .error_value => {
                    const name_token = ast.nodeMainToken(node) + 2;
                    if (@as(usize, name_token) < tags.len and tags[name_token] == .identifier and
                        !inTestRange(name_token, test_ranges.items))
                    {
                        try addName(allocator, &names, ast.tokenSlice(name_token));
                    }
                },
                else => {},
            }
        }
    }

    if (names.count() == 0) {
        std.debug.print("gen_zerr: no error names found under {s}\n", .{std_dir});
        std.process.exit(1);
    }

    const list = try allocator.alloc([]const u8, names.count());
    defer allocator.free(list);
    var n: usize = 0;
    var it = names.keyIterator();
    while (it.next()) |key| : (n += 1) list[n] = key.*;
    std.sort.pdq([]const u8, list, {}, lessThan);

    var out = std.Io.Writer.Allocating.init(allocator);
    defer out.deinit();
    const w = &out.writer;
    try w.writeAll(header);
    for (list, 0..) |name, i| {
        try w.print("    {s}", .{name});
        if (i + 1 < list.len) try w.writeByte(',');
        try w.writeByte('\n');
    }
    try w.writeAll("}\n");
    const text = out.written();

    if (check) {
        const committed = std.Io.Dir.cwd().readFileAlloc(
            init.io,
            out_path,
            allocator,
            .limited(max_file_bytes),
        ) catch |err| {
            std.debug.print("gen_zerr: cannot read {s}: {s}\n", .{ out_path, @errorName(err) });
            std.process.exit(1);
        };
        // A Windows checkout may have converted the committed file to CRLF.
        // The generated text is LF; compare content, not line endings.
        const normalized = try allocator.alloc(u8, committed.len);
        var normalized_len: usize = 0;
        for (committed) |c| {
            if (c == '\r') continue;
            normalized[normalized_len] = c;
            normalized_len += 1;
        }
        if (!std.mem.eql(u8, normalized[0..normalized_len], text)) {
            std.debug.print("gen_zerr: {s} is stale; run `zig build zerr`\n", .{out_path});
            std.process.exit(1);
        }
        std.debug.print("gen_zerr: {s} is current ({d} names)\n", .{ out_path, list.len });
        return;
    }

    if (std.fs.path.dirname(out_path)) |parent| {
        std.Io.Dir.cwd().createDirPath(init.io, parent) catch |err| {
            std.debug.print("gen_zerr: cannot create {s}: {s}\n", .{ parent, @errorName(err) });
            std.process.exit(1);
        };
    }
    std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = out_path, .data = text }) catch |err| {
        std.debug.print("gen_zerr: cannot write {s}: {s}\n", .{ out_path, @errorName(err) });
        std.process.exit(1);
    };
    std.debug.print("gen_zerr: wrote {s} ({d} names from {d} files)\n", .{ out_path, list.len, file_count });
}

const TokenRange = struct {
    start: std.zig.Ast.TokenIndex,
    end: std.zig.Ast.TokenIndex,
};

fn inTestRange(t: std.zig.Ast.TokenIndex, ranges: []const TokenRange) bool {
    for (ranges) |range| {
        if (t >= range.start and t <= range.end) return true;
    }
    return false;
}

fn addName(allocator: std.mem.Allocator, names: *std.StringHashMap(void), name: []const u8) !void {
    if (name.len == 0) return;
    if (!std.ascii.isAlphabetic(name[0]) and name[0] != '_') return;
    for (name[1..]) |c| {
        if (!std.ascii.isAlphanumeric(c) and c != '_') return;
    }
    if (names.get(name) != null) return;
    try names.put(try allocator.dupe(u8, name), {});
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}
